#!/bin/bash

# Run from the results directory. Reduces each run's newest perf/ run
# directory again (for a run whose in-job reduction failed).
REDUCE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../2026-WOIV-scripts/reduce_timers.py"

# Array to keep track of failures
FAILED_RUNS=()

# --- HELPER FUNCTION ---
# Checks if the directory exists, runs the python script, 
# and records a failure if the script crashes or errors out.
run_reduction() {
    local DIR="$1"
    local OUT="$2"

    if [ ! -d "$DIR" ]; then
        echo "Skipping: Directory not found -> $DIR"
        FAILED_RUNS+=("$DIR (Directory not found)")
        return
    fi
    # One attempt only: the newest run directory under perf/.
    local RUN
    RUN=$(ls -dt "$DIR"/*/ 2>/dev/null | head -1)
    if [ -z "$RUN" ]; then
        echo "Skipping: no run directory in $DIR"
        FAILED_RUNS+=("$DIR (No run directory)")
        return
    fi

    # Run the script. If it fails (returns non-zero), the 'else' block triggers.
    if python "$REDUCE" "$RUN" "$OUT"; then
        echo "Success: $DIR"
    else
        echo "FAILED: Error processing -> $DIR"
        FAILED_RUNS+=("$DIR (Processing failed)")
    fi
}

# --- WORKLOAD DEFINITIONS ---
# All workloads generated by the new orchestrator
WORKLOADS=(
    "baseline"
    "adios_data"
    "ascent_data" "ascent_render" "ascent_volume" "ascent_isosurface"
    "catalyst_data" "catalyst_render" "catalyst_volume" "catalyst_isosurface"
)

# --- STRONG SCALING RUNS ---
echo -e "\nProcessing Strong Scaling Runs..."
for N in 0256 1024 4096; do
    for TYPE in "${WORKLOADS[@]}"; do
        DIR="paper2_strong_N${N}_${TYPE}/perf/"
        OUT="summary_strong_N${N}_${TYPE}.csv"
        
        run_reduction "$DIR" "$OUT"
    done
done

# --- WEAK SCALING RUNS ---
echo -e "\nProcessing Weak Scaling Runs..."
for N in 0008 0064 0512 4096; do
    for TYPE in "${WORKLOADS[@]}"; do
        DIR="paper2_weak_N${N}_${TYPE}/perf/"
        OUT="summary_weak_N${N}_${TYPE}.csv"
        
        run_reduction "$DIR" "$OUT"
    done
done

# --- TRANSIT RUNS (Standard: Small, Compressed, Hero) ---
echo -e "\nProcessing Standard Transit Runs..."
for SCALE in "small_N0064" "compressed_N0512" "hero_N4096"; do
    for TYPE in "${WORKLOADS[@]}"; do
        # Baseline doesn't run in transit, skip it
        if [ "$TYPE" == "baseline" ]; then continue; fi

        DIR="paper2_transit_${SCALE}_${TYPE}/perf/"
        OUT="summary_transit_${SCALE}_${TYPE}.csv"
        
        run_reduction "$DIR" "$OUT"
    done
done

# --- TRANSIT RUNS (Carte Blanche Sweeps) ---
echo -e "\nProcessing Transit Sweep Runs..."
for SWEEP in "sweep_64_N4096_S064" "sweep_128_N4096_S128" "sweep_384_N4096_S384"; do
    for TYPE in "${WORKLOADS[@]}"; do
        if [ "$TYPE" == "baseline" ]; then continue; fi

        DIR="paper2_transit_${SWEEP}_${TYPE}/perf/"
        OUT="summary_transit_${SWEEP}_${TYPE}.csv"
        
        run_reduction "$DIR" "$OUT"
    done
done


# --- SUMMARY REPORT ---
echo -e "\n================================================"
echo "All reduction tasks complete."

# Check if the FAILED_RUNS array is empty
if [ ${#FAILED_RUNS[@]} -eq 0 ]; then
    echo "🎉 All runs processed successfully!"
    exit 0
else
    echo "⚠️  The following runs FAILED or were SKIPPED:"
    for failed in "${FAILED_RUNS[@]}"; do
        echo "  - $failed"
    done
    exit 1 # Exit with an error code so you know the overall job had issues
fi
